import path from 'node:path';

function manifestEvents(manifest, tagName) {
  const declarations = manifest.modules.flatMap(
    (module) => module.declarations ?? []
  );
  const matches = declarations.filter(
    (declaration) => declaration.tagName === tagName
  );
  if (matches.length !== 1) {
    throw new Error(
      `Resolve one manifest declaration for ${tagName}; found ${matches.length}.`
    );
  }
  return matches[0].events ?? [];
}

export function reactEventRegistry(wrappers, manifest, model) {
  return wrappers.map((wrapper) => {
    const published = manifestEvents(manifest, wrapper.element.tagName);
    const events = wrapper.callbacks.map((binding) => {
      const matches = published.filter(
        (event) => event.name === binding.eventName
      );
      if (
        matches.length !== 1 ||
        !matches[0].description?.trim() ||
        !matches[0].type?.text?.trim()
      ) {
        throw new Error(
          `${wrapper.location}: Resolve one described, typed CEM event for ${binding.callback} (${binding.eventName}).`
        );
      }
      const event = matches[0];
      return {
        callback: binding.callback,
        eventName: event.name,
        description: event.description,
        type: event.type.text,
      };
    });
    const source = model?.program.getSourceFile(
      path.join(model.root, wrapper.module)
    );
    const module = source && model.checker.getSymbolAtLocation(source);
    let symbol =
      module &&
      model.checker
        .getExportsOfModule(module)
        .find((entry) => entry.name === wrapper.exportName);
    if (symbol && symbol.flags & model.ts.SymbolFlags.Alias) {
      symbol = model.checker.getAliasedSymbol(symbol);
    }
    const declaration = symbol?.valueDeclaration ?? symbol?.declarations?.[0];
    const identity = declaration
      ? `${path.relative(model.root, declaration.getSourceFile().fileName)}:${declaration.getStart()}`
      : `${wrapper.module}#${wrapper.exportName}`;
    return {
      module: wrapper.module,
      exportName: wrapper.exportName,
      identity,
      tagName: wrapper.element.tagName,
      events,
    };
  });
}

export function renderReactRegistry(registry, directory) {
  const imports = registry.map((entry, index) => {
    let module = path.relative(directory, entry.module).replaceAll('\\', '/');
    if (!module.startsWith('.')) {
      module = `./${module}`;
    }
    module = module.replace(/\.tsx?$/, '.js');
    return `import { ${entry.exportName === 'default' ? 'default' : entry.exportName} as component${index} } from ${JSON.stringify(module)};`;
  });
  const entries = registry.map(
    (entry, index) =>
      `{ component: component${index}, ...${JSON.stringify(entry)} }`
  );
  return `/* Generated by manifest-react-docs.js. */\n${imports.join('\n')}\n\nexport const entries = [\n${entries.join(',\n')}\n];\n`;
}
